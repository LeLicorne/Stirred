import Foundation

public enum PEArchitecture: Sendable, Equatable {
    case x86, x64, arm64, unknown
}

/// Reads just enough of a Windows executable (PE) header to know its CPU architecture.
public enum PEInfo {
    public static func architecture(of header: Data) -> PEArchitecture {
        guard header.count >= 0x40, header[0] == 0x4D, header[1] == 0x5A else { return .unknown }   // "MZ"
        let peOffset = Int(header[0x3C]) | Int(header[0x3D]) << 8 | Int(header[0x3E]) << 16 | Int(header[0x3F]) << 24
        guard peOffset >= 0, peOffset + 6 <= header.count,
              header[peOffset] == 0x50, header[peOffset + 1] == 0x45,
              header[peOffset + 2] == 0, header[peOffset + 3] == 0 else { return .unknown }       // "PE\0\0"
        let machine = Int(header[peOffset + 4]) | Int(header[peOffset + 5]) << 8
        switch machine {
        case 0x014C: return .x86
        case 0x8664: return .x64
        case 0xAA64: return .arm64
        default: return .unknown
        }
    }

    public static func architecture(ofFile url: URL) -> PEArchitecture {
        guard let handle = try? FileHandle(forReadingFrom: url) else { return .unknown }
        defer { try? handle.close() }
        return architecture(of: (try? handle.read(upToCount: 4096)) ?? Data())
    }
}

/// How much input latency we trade for smoothness/throughput. Each frame queued ahead adds ~16 ms at 60 Hz.
public enum LatencyProfile: String, Codable, Sendable, CaseIterable {
    case balanced   // 2 frames queued, V-Sync as the game asks
    case low        // 1 frame queued, V-Sync as the game asks
    case lowest     // 1 frame queued, V-Sync forced off (tearing possible)
}

public enum DXVKConfig {
    /// Contents of the per-game `dxvk.conf` for a latency profile.
    public static func render(latency: LatencyProfile, hud: Bool = false, asyncShaders: Bool = false, extra: [String: String] = [:]) -> String {
        var lines = ["# Generated by Stirred (latency profile: \(latency.rawValue)). Safe to delete."]
        switch latency {
        case .balanced:
            lines.append("dxgi.maxFrameLatency = 2")
        case .low:
            lines.append("dxgi.maxFrameLatency = 1")
        case .lowest:
            lines.append("dxgi.maxFrameLatency = 1")
            lines.append("dxgi.syncInterval = 0")
            lines.append("dxgi.tearFree = False")
        }
        // Shader compilation in the background: removes first-use stutter, may briefly hide objects.
        if asyncShaders { lines.append("dxvk.enableAsync = True") }
        // On-screen fps + frame-time graph, to measure instead of guessing.
        if hud { lines.append("dxvk.hud = fps,frametimes") }
        // Per-game settings from the recipe (sorted so the file is stable).
        for (key, value) in extra.sorted(by: { $0.key < $1.key }) { lines.append("\(key) = \(value)") }
        return lines.joined(separator: "\n") + "\n"
    }
}

/// Installs DXVK next to a game executable and tells Wine to prefer those DLLs for that executable only.
/// Why per-executable: Steam is already running when a game starts, so per-game environment variables never
/// reach the game; and a global override would also affect the Steam client itself.
public enum DXVKInstaller {
    public static let dlls = ["d3d11.dll", "dxgi.dll", "d3d10core.dll"]

    /// `package` is a folder containing `x32/` and `x64/` (the DXVK release layout).
    @discardableResult
    public static func install(
        package: URL, executable: URL, architecture: PEArchitecture, latency: LatencyProfile = .low,
        hud: Bool = false, asyncShaders: Bool = false, extra: [String: String] = [:]
    ) throws -> [URL] {
        let subdirectory: String
        switch architecture {
        case .x86: subdirectory = "x32"
        case .x64: subdirectory = "x64"
        default: throw StirredError.blocked("Cannot install DXVK for an executable with unknown architecture.")
        }
        let source = package.appendingPathComponent(subdirectory, isDirectory: true)
        let destination = executable.deletingLastPathComponent()
        var copied: [URL] = []
        for name in dlls {
            let from = source.appendingPathComponent(name)
            let to = destination.appendingPathComponent(name)
            if FileManager.default.fileExists(atPath: to.path) { try FileManager.default.removeItem(at: to) }
            try FileManager.default.copyItem(at: from, to: to)
            copied.append(to)
        }
        // DXVK reads dxvk.conf from the executable's directory: per-game settings, no environment needed.
        try DXVKConfig.render(latency: latency, hud: hud, asyncShaders: asyncShaders, extra: extra).write(
            to: destination.appendingPathComponent("dxvk.conf"), atomically: true, encoding: .utf8)
        return copied
    }

    /// `wine reg add ...` argument lists that make Wine load our native DLLs for this executable only.
    public static func registryCommands(executableName: String) -> [[String]] {
        dlls.map { dll in
            ["reg", "add", "HKCU\\Software\\Wine\\AppDefaults\\\(executableName)\\DllOverrides",
             "/v", String(dll.dropLast(4)), "/d", "native,builtin", "/f"]
        }
    }
}

public enum GameExecutableFinder {
    private static let ignoredFragments = ["crash", "unins", "setup", "redist", "vcredist", "dxsetup", "helper", "launcher_"]

    /// Likely game executables: Unreal's real executable first (`<Project>/Binaries/Win64/*-Win64-Shipping.exe`, the
    /// top-level .exe is only a launcher stub), then .exe files at the top of the install directory
    /// (skipping crash handlers, installers...).
    public static func candidates(in directory: URL) -> [URL] {
        let fm = FileManager.default
        let children = (try? fm.contentsOfDirectory(at: directory, includingPropertiesForKeys: [.isDirectoryKey])) ?? []
        var unreal: [URL] = []
        for child in children where child.hasDirectoryPath && child.lastPathComponent != "Engine" {
            let bin = child.appendingPathComponent("Binaries/Win64", isDirectory: true)
            let shipping = ((try? fm.contentsOfDirectory(at: bin, includingPropertiesForKeys: nil)) ?? [])
                .filter { $0.lastPathComponent.hasSuffix("-Win64-Shipping.exe") }
            unreal.append(contentsOf: shipping)
        }
        let top = children.filter { url in
            let name = url.lastPathComponent.lowercased()
            return url.pathExtension.lowercased() == "exe" && !ignoredFragments.contains { name.contains($0) }
        }
        return unreal + top
    }
}
